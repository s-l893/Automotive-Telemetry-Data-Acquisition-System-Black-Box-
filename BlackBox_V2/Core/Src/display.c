void LCD_DrawChar(uint16_t x, uint16_t y, char c, uint16_t fg, uint16_t bg, uint8_t scale)
{
	uint8_t ramwr = 0x2C;
	uint16_t gw;
	uint16_t gh;
	const uint8_t *glyph;
	uint8_t strip[80];
	uint8_t fg_hi = (uint8_t)(fg >> 8);
	uint8_t fg_lo = (uint8_t)(fg & 0xFF);
	uint8_t bg_hi = (uint8_t)(bg >> 8);
	uint8_t bg_lo = (uint8_t)(bg & 0xFF);

	if (scale == 0) {
		scale = 1;
	}
	if (scale > 5) {
		scale = 5;
	}
	if (c < 32 || c > 127) {
		c = '?';
	}

	glyph = font8x8_basic[c - 32];
	gw = (uint16_t)(8U * scale);
	gh = (uint16_t)(8U * scale);

	if ((uint32_t)x + gw > LCD_WIDTH || (uint32_t)y + gh > LCD_HEIGHT) {
		return;
	}

	/*
	 * SetWindow_Logical maps landscape -> native with both axes inverted.
	 * Hardware fill order is columns right->left, within each column bottom->top.
	 */
	LCD_SetWindow_Logical(x, y, (uint16_t)(x + gw - 1U), (uint16_t)(y + gh - 1U));
	LCD_CS_Low();
	LCD_DC_Low();
	HAL_SPI_Transmit(&hspi1, &ramwr, 1, HAL_MAX_DELAY);
	LCD_DC_High();

	for (int8_t col = 7; col >= 0; col--) {
		for (int8_t sx = (int8_t)scale - 1; sx >= 0; sx--) {
			uint16_t o = 0;
			for (int8_t row = 7; row >= 0; row--) {
				uint8_t on = (glyph[(uint8_t)col] & (1U << (uint8_t)row)) ? 1U : 0U;
				uint8_t hi = on ? fg_hi : bg_hi;
				uint8_t lo = on ? fg_lo : bg_lo;
				for (int8_t sy = (int8_t)scale - 1; sy >= 0; sy--) {
					strip[o++] = hi;
					strip[o++] = lo;
					(void)sy;
				}
			}
			LCD_Send_Data(strip, o);
			(void)sx;
		}
		HAL_IWDG_Refresh(&hiwdg);
	}

	LCD_CS_High();
}

void LCD_DrawString(uint16_t x, uint16_t y, const char *s, uint16_t fg, uint16_t bg, uint8_t scale)
{
	uint16_t cx = x;
	uint16_t advance = (uint16_t)(8U * (scale ? scale : 1U));

	if (s == NULL) {
		return;
	}
	while (*s) {
		LCD_DrawChar(cx, y, *s, fg, bg, scale);
		cx = (uint16_t)(cx + advance);
		if (cx >= LCD_WIDTH) {
			break;
		}
		s++;
	}
}

void LCD_DrawTextField(uint16_t x, uint16_t y, uint16_t w, uint16_t h,
		uint16_t bg, uint16_t fg, uint8_t scale, const char *s)
{
	LCD_FillRect(x, y, w, h, bg);
	LCD_DrawString(x, y, s, fg, bg, scale);
	HAL_IWDG_Refresh(&hiwdg);
}

void LCD_DrawBitmap1bpp(uint16_t x, uint16_t y, uint16_t w, uint16_t h,
		const uint8_t *bits, uint16_t fg, uint16_t bg)
{
	uint8_t ramwr = 0x2C;
	uint16_t row_bytes;
	uint8_t strip[64];
	uint8_t fg_hi = (uint8_t)(fg >> 8);
	uint8_t fg_lo = (uint8_t)(fg & 0xFF);
	uint8_t bg_hi = (uint8_t)(bg >> 8);
	uint8_t bg_lo = (uint8_t)(bg & 0xFF);

	if (bits == NULL || w == 0 || h == 0) {
		return;
	}
	if ((uint32_t)x + w > LCD_WIDTH || (uint32_t)y + h > LCD_HEIGHT) {
		return;
	}
	if (h > 32) {
		return;
	}

	row_bytes = (uint16_t)((w + 7U) / 8U);
	LCD_SetWindow_Logical(x, y, (uint16_t)(x + w - 1U), (uint16_t)(y + h - 1U));
	LCD_CS_Low();
	LCD_DC_Low();
	HAL_SPI_Transmit(&hspi1, &ramwr, 1, HAL_MAX_DELAY);
	LCD_DC_High();

	for (int16_t col = (int16_t)w - 1; col >= 0; col--) {
		uint16_t o = 0;
		for (int16_t row = (int16_t)h - 1; row >= 0; row--) {
			const uint8_t *rowptr = bits + ((uint16_t)row * row_bytes);
			uint8_t byte = rowptr[(uint16_t)col / 8U];
			uint8_t on = (byte & (0x80U >> ((uint16_t)col & 7U))) ? 1U : 0U;
			strip[o++] = on ? fg_hi : bg_hi;
			strip[o++] = on ? fg_lo : bg_lo;
		}
		LCD_Send_Data(strip, o);
	}

	LCD_CS_High();
}
